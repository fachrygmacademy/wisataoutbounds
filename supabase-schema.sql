-- 1. Buat tabel 'kontak' jika belum ada
CREATE TABLE IF NOT EXISTS public.kontak (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama TEXT NOT NULL,
    email TEXT,
    telepon TEXT NOT NULL,
    nama_instansi TEXT,
    paket TEXT NOT NULL,
    jumlah_peserta INT,
    tanggal_kegiatan DATE,
    pesan TEXT,
    status TEXT DEFAULT 'baru',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Berikan komentar dokumentasi pada tabel & kolom
COMMENT ON TABLE public.kontak IS 'Tabel data kontak pemesan dan pembeli paket outbound';
COMMENT ON COLUMN public.kontak.nama IS 'Nama lengkap pemesan atau PIC instansi';
COMMENT ON COLUMN public.kontak.email IS 'Alamat email pemesan';
COMMENT ON COLUMN public.kontak.telepon IS 'Nomor WhatsApp atau handphone untuk konfirmasi';
COMMENT ON COLUMN public.kontak.nama_instansi IS 'Nama perusahaan, sekolah, atau komunitas pemesan';
COMMENT ON COLUMN public.kontak.paket IS 'Nama paket outbound yang dibeli / dipesan';
COMMENT ON COLUMN public.kontak.jumlah_peserta IS 'Estimasi jumlah peserta kegiatan';
COMMENT ON COLUMN public.kontak.tanggal_kegiatan IS 'Estimasi tanggal pelaksanaan kegiatan';
COMMENT ON COLUMN public.kontak.pesan IS 'Catatan khusus, preferensi venue, atau detail permintaan';
COMMENT ON COLUMN public.kontak.status IS 'Status follow-up pesanan: baru, diproses, selesai, dibatalkan';
COMMENT ON COLUMN public.kontak.created_at IS 'Waktu pesanan masuk ke database';

-- 3. Aktifkan Row Level Security (RLS) demi keamanan data
ALTER TABLE public.kontak ENABLE ROW LEVEL SECURITY;

-- 4. Kebijakan RLS (Policy 1):
-- Izinkan siapapun (anon / pengunjung website) untuk menambahkan data (INSERT)
CREATE POLICY "Izinkan pengunjung mengirim data kontak"
ON public.kontak
FOR INSERT
TO anon, authenticated
WITH CHECK (true);

-- 5. Kebijakan RLS (Policy 2):
-- Hanya pengguna terautentikasi (admin di dashboard Supabase) yang dapat melihat/membaca (SELECT)
CREATE POLICY "Izinkan admin melihat data kontak"
ON public.kontak
FOR SELECT
TO authenticated
USING (true);

-- 6. Kebijakan RLS (Policy 3):
-- Hanya admin yang dapat mengubah status (UPDATE)
CREATE POLICY "Izinkan admin mengubah data kontak"
ON public.kontak
FOR UPDATE
TO authenticated
USING (true)
WITH CHECK (true);

-- 7. Kebijakan RLS (Policy 4):
-- Hanya admin yang dapat menghapus (DELETE)
CREATE POLICY "Izinkan admin menghapus data kontak"
ON public.kontak
FOR DELETE
TO authenticated
USING (true);
